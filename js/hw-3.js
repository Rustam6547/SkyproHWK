let monthNumber = prompt ('Введите порядковый номер месяца '); // Задаем номер месяца

if (monthNumber > 12) {
    console.log("Номер месяца должен быть от 1 до 12.");
} else {
    switch (monthNumber) {
        case 1: // Январь
        case 2: // Февраль
        case 12: // Декабрь
            console.log("Зима");
            break;
        case 3: // Март
        case 4: // Апрель
        case 5: // Май
            console.log("Весна");
            break;
        case 6: // Июнь
        case 7: // Июль
        case 8: // Август
            console.log("Лето");
            break;
        case 9: // Сентябрь
        case 10: // Октябрь
        case 11: // Ноябрь
            console.log("Осень");
            break;
        default:
            console.log("Неверный номер месяца.");
            break;
    }
}


